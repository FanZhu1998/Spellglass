// Generates precompiled validators from the JSON Schemas in src/contracts/schemas.
//
// Why: the schemas are the source of truth for pack checking (blueprint Section 12), but the app's
// content security policy forbids eval and new Function (index.html: script-src 'self'), so Ajv may
// not compile schemas in the browser. Ajv's standalone mode compiles them here, at build time, into a
// plain ES module: src/kernel/packs/generated/validators.js, with a small validators.d.ts beside it.
// 'npm run gen' runs this before 'npm run build' and 'npm test'. The folder is git-ignored.
//
// Usage:
//   node tools/gen-validators.mjs           write the validators (only files whose content changed)
//   node tools/gen-validators.mjs --check   exit 1 if the validators are missing or out of date
//
// It is idempotent (the same schemas give byte-identical output) and takes well under a second.

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';

export const SCHEMA_DIR = new URL('../src/contracts/schemas/', import.meta.url);
export const OUT_DIR = new URL('../src/kernel/packs/generated/', import.meta.url);

/** Exported validator name → schema reference. A '#/definitions/...' fragment exports one definition. */
export const EXPORTS = {
  validateSpellPack0: 'spellpack-0.json',
  validateSpellPack1: 'spellpack-1.json',
  validateThemePack1: 'themepack-1.json',
  validateGesturePack1: 'gesturepack-1.json',
  validatePackIndex1: 'packindex-1.json',
  validatePackIndexEntry1: 'packindex-1.json#/definitions/entry',
  validateGesture1: 'common-1.json#/definitions/gesture',
  validateSession1: 'session-1.json',
  validateUserData1: 'userdata-1.json',
};

/** The schema files, sorted, with their bytes. */
export function readSchemas(dir = SCHEMA_DIR) {
  return readdirSync(dir)
    .filter((name) => name.endsWith('.json'))
    .sort()
    .map((name) => ({ name, bytes: readFileSync(new URL(name, dir)) }));
}

/** A digest of everything the output depends on: the schema files and this generator. The generated
 *  module exports it as SCHEMA_FINGERPRINT, so a test can tell when someone forgot 'npm run gen'. */
export function schemaFingerprint(schemas = readSchemas()) {
  const hash = createHash('sha256');
  for (const { name, bytes } of schemas) {
    hash.update(name);
    hash.update('\n');
    hash.update(bytes);
    hash.update('\n');
  }
  hash.update(readFileSync(fileURLToPath(import.meta.url)));
  return hash.digest('hex');
}

/** Ajv as the app needs it. These options are part of the build contract:
 *  - code.esm: an ES module, since Vite bundles ES modules.
 *  - unicode: false: string lengths count UTF-16 code units. With the default, Ajv 8.20 emits
 *    require("ajv/dist/runtime/ucs2length") even in ESM output, which a browser cannot load. Ajv logs
 *    that the option is deprecated; it is still honoured, and the logger below drops that one line.
 *  - allowUnionTypes: lets type: ["string", "null"] through strict mode (session and data schemas).
 *  The schemas also avoid uniqueItems, format, and const or enum with object values, which would pull
 *  in other runtime helpers. The output is checked for require( below in any case. */
export function createAjv() {
  return new Ajv({
    code: { source: true, esm: true },
    strict: true,
    allErrors: true,
    unicode: false,
    allowUnionTypes: true,
    logger: {
      log() {},
      warn(...args) {
        if (!String(args[0]).includes('option unicode')) console.warn(...args);
      },
      error: console.error,
    },
  });
}

const HEADER =
  '// GENERATED by tools/gen-validators.mjs from src/contracts/schemas. Do not edit.\n' +
  "// Run 'npm run gen' after changing a schema.\n";

function declarations() {
  const names = Object.keys(EXPORTS);
  return (
    HEADER +
    '\n' +
    '/** One problem found by a validator (Ajv error object). */\n' +
    'export interface SchemaError {\n' +
    '  instancePath: string;\n' +
    '  schemaPath: string;\n' +
    '  keyword: string;\n' +
    '  params: Record<string, unknown>;\n' +
    '  propertyName?: string;\n' +
    '  message?: string;\n' +
    '}\n\n' +
    '/** Returns true when data matches; otherwise false, with the problems in errors. */\n' +
    'export interface SchemaValidator {\n' +
    '  (data: unknown): boolean;\n' +
    '  errors?: SchemaError[] | null;\n' +
    '}\n\n' +
    names.map((n) => `/** ${EXPORTS[n]} */\nexport declare const ${n}: SchemaValidator;\n`).join('') +
    '\n/** Digest of the schemas and generator this file was made from. */\n' +
    'export declare const SCHEMA_FINGERPRINT: string;\n'
  );
}

/** Compile every schema and return the two output files' contents. Throws with a plain message. */
export function generate(schemas = readSchemas()) {
  const ajv = createAjv();
  for (const { name, bytes } of schemas) {
    let schema;
    try {
      schema = JSON.parse(bytes.toString('utf8'));
    } catch (err) {
      throw new Error(`${name} is not valid JSON: ${err.message}`);
    }
    // Relative $refs between the files resolve against each schema's $id, so the $id must be the
    // file's own name. Then the files work the same in any JSON Schema tool that loads them from disk.
    if (schema.$id !== name) throw new Error(`${name} must have "$id": "${name}" (it has ${JSON.stringify(schema.$id)})`);
    ajv.addSchema(schema);
  }
  for (const [exportName, ref] of Object.entries(EXPORTS)) {
    if (!ajv.getSchema(ref)) throw new Error(`${exportName}: cannot resolve ${ref}`);
  }
  const code = standaloneCode(ajv, EXPORTS);
  if (code.includes('require(')) {
    throw new Error('the generated validators call require(), which browsers cannot load. Remove the schema keyword that needs an Ajv runtime helper (format, uniqueItems, or const/enum with object values).');
  }
  const js = HEADER + code + `\nexport const SCHEMA_FINGERPRINT = ${JSON.stringify(schemaFingerprint(schemas))};\n`;
  return { 'validators.js': js, 'validators.d.ts': declarations() };
}

function writeIfChanged(file, text) {
  if (existsSync(file) && readFileSync(file, 'utf8') === text) return false;
  writeFileSync(file, text);
  return true;
}

function main(argv) {
  const check = argv.includes('--check');
  const started = performance.now();
  let files;
  try {
    files = generate();
  } catch (err) {
    console.error(`gen-validators: ${err.message}`);
    process.exit(1);
  }
  if (check) {
    const stale = Object.entries(files).filter(([name, text]) => {
      const file = new URL(name, OUT_DIR);
      return !existsSync(file) || readFileSync(file, 'utf8') !== text;
    });
    if (stale.length) {
      console.error(`gen-validators: out of date (${stale.map(([n]) => n).join(', ')}). Run 'npm run gen'.`);
      process.exit(1);
    }
    console.log('gen-validators: up to date');
    return;
  }
  mkdirSync(OUT_DIR, { recursive: true });
  const written = Object.entries(files).filter(([name, text]) => writeIfChanged(new URL(name, OUT_DIR), text));
  const ms = Math.round(performance.now() - started);
  const kb = Math.round(files['validators.js'].length / 1024);
  console.log(
    written.length
      ? `gen-validators: wrote ${written.map(([n]) => n).join(', ')} (${kb} KB, ${ms} ms)`
      : `gen-validators: up to date (${kb} KB, ${ms} ms)`,
  );
}

// Run only when executed directly, so tests can import the functions above. Paths are compared
// without regard to case on Windows, where a shell may report the drive as c: and Node as C:.
function isMain() {
  if (!process.argv[1]) return false;
  const norm = (p) => (process.platform === 'win32' ? p.toLowerCase() : p);
  let entry = process.argv[1];
  try {
    entry = realpathSync(entry);
  } catch {
    /* keep the path as given */
  }
  return norm(fileURLToPath(import.meta.url)) === norm(fileURLToPath(pathToFileURL(entry)));
}
if (isMain()) main(process.argv.slice(2));
